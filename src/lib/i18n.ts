const dicts: Record<Lang, Record<I18nKey, string>> = { zh, en }
let current: Lang = 'zh'

export const getLang = () => current
export function setLang(l: Lang | undefined) {
  current = l && l in dicts ? l : 'zh'
  document.documentElement.lang = current === 'zh' ? 'zh-CN' : 'en'
}

export function t(key: I18nKey, vars?: Record<string, string | number>) {
  const s = dicts[current][key] ?? zh[key] ?? key
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s
}

export const locale = () => (current === 'zh' ? 'zh-CN' : 'en-US')
